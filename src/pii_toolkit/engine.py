"""Policy engine: apply a validated policy to a DataFrame.

The engine builds the protected DataFrame and an `AuditRecord`, but does not write the audit
log itself. The caller appends the record *after* the output is safely written, so the log never
claims a run that did not land.
"""

from __future__ import annotations

import logging
import os
from dataclasses import dataclass, field

from pyspark.sql import Column, DataFrame
from pyspark.sql import functions as F

from pii_toolkit.audit import AuditRecord, current_actor
from pii_toolkit.detect import Finding, unmapped_findings
from pii_toolkit.envelope import DataKey, KeyManager
from pii_toolkit.policy import ColumnRule, Policy, PolicyError
from pii_toolkit.rules import (
    DEK_COLUMN,
    encrypt_column,
    hash_column,
    mask_column,
    nullify_column,
    tokenise_column,
)
from pii_toolkit.vault import TokenVault

log = logging.getLogger(__name__)

MIN_SECRET_LENGTH = 16


@dataclass(frozen=True)
class Secrets:
    """Salt and HMAC key. Read from the environment; never from the policy file."""

    hash_salt: str = field(repr=False)
    token_key: bytes = field(repr=False)

    @classmethod
    def from_env(cls, policy: Policy) -> Secrets:
        salt = os.environ.get(policy.hash_salt_env, "")
        token_key = os.environ.get(policy.token_key_env, "")
        rules = {c.rule for c in policy.columns}
        problems = []
        if "hash" in rules and len(salt) < MIN_SECRET_LENGTH:
            problems.append(f"{policy.hash_salt_env} must be set (>= {MIN_SECRET_LENGTH} chars)")
        if "tokenise" in rules and len(token_key) < MIN_SECRET_LENGTH:
            problems.append(f"{policy.token_key_env} must be set (>= {MIN_SECRET_LENGTH} chars)")
        if problems:
            raise RuntimeError("; ".join(problems))
        return cls(hash_salt=salt, token_key=token_key.encode("utf-8"))


@dataclass
class ProtectionResult:
    df: DataFrame
    audit_record: AuditRecord
    unmapped: list[Finding]


def apply_policy(
    df: DataFrame,
    policy: Policy,
    secrets: Secrets,
    key_manager: KeyManager | None = None,
    vault: TokenVault | None = None,
    actor: str | None = None,
    source: str = "",
    destination: str = "",
    strict: bool = True,
) -> ProtectionResult:
    """Return the protected DataFrame plus the audit record describing what was done.

    strict=True (the default) fails if the policy names a column the input lacks: a renamed
    upstream column would otherwise pass through unprotected under its new name.
    """
    missing = [c for c in policy.column_names if c not in df.columns]
    if missing and strict:
        raise PolicyError([f"column '{c}' is in the policy but not in the input" for c in missing])
    applied = [c for c in policy.columns if c.column in df.columns]

    unmapped = unmapped_findings(df, policy)

    if any(c.rule == "tokenise" and c.options["vault"] for c in applied):
        if vault is None:
            raise ValueError("policy tokenises into a vault but no TokenVault was supplied")
        _record_tokens(df, applied, secrets, vault)

    data_key = None
    if any(c.rule == "encrypt" for c in applied):
        if key_manager is None:
            raise ValueError("policy uses 'encrypt' but no KeyManager was supplied")
        data_key = key_manager.generate_data_key()  # one data key per batch

    exprs: list[Column] = []
    for name in df.columns:
        rule = policy.rule_for(name)
        if rule is None:
            exprs.append(F.col(name))
            continue
        exprs.append(_expression(rule, F.col(name), df, secrets, data_key).alias(name))
    if data_key is not None:
        exprs.append(F.lit(data_key.header()).alias(DEK_COLUMN))

    protected = df.select(*exprs)
    record = AuditRecord(
        actor=actor or current_actor(),
        policy_name=policy.name,
        policy_hash=policy.policy_hash,
        columns={c.column: c.rule for c in applied},
        row_count=df.count(),
        source=source,
        destination=destination,
        unmapped_pii_columns=sorted({f.column for f in unmapped}),
    )
    return ProtectionResult(df=protected, audit_record=record, unmapped=unmapped)


def _expression(
    rule: ColumnRule, col: Column, df: DataFrame, secrets: Secrets, data_key: DataKey | None
) -> Column:
    match rule.rule:
        case "hash":
            return hash_column(col, secrets.hash_salt)
        case "tokenise":
            return tokenise_column(col, secrets.token_key)
        case "mask":
            return mask_column(col, rule.options["keep_last"], rule.options["mask_char"])
        case "nullify":
            return nullify_column(df.schema[rule.column].dataType)
        case "encrypt":
            assert data_key is not None  # generated by apply_policy whenever encrypt is used
            return encrypt_column(col, data_key, rule.column)
    raise AssertionError(f"unhandled rule {rule.rule}")  # policy validation prevents this


def _record_tokens(
    df: DataFrame, rules: list[ColumnRule], secrets: Secrets, vault: TokenVault
) -> None:
    """Write token -> value pairs for every vaulted column before the values are replaced."""
    pairs = None
    for rule in rules:
        if rule.rule != "tokenise" or not rule.options["vault"]:
            continue
        part = df.select(
            F.lit(rule.column).alias("column_name"),
            tokenise_column(F.col(rule.column), secrets.token_key).alias("token"),
            F.col(rule.column).cast("string").alias("value"),
        )
        pairs = part if pairs is None else pairs.unionByName(part)
    if pairs is not None:
        added = vault.record(pairs)
        log.info("token vault: %d new tokens", added)
